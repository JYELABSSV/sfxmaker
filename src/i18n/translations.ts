/**
 * Detect browser language and map to supported language
 */
export function detectBrowserLanguage(): Exclude<SupportedLanguage, 'auto'> {
  if (typeof navigator === 'undefined') return 'ko';

  const navLang = (navigator.language || (navigator as { userLanguage?: string }).userLanguage || '').toLowerCase();

  if (navLang.startsWith('ko')) return 'ko';
  if (navLang.startsWith('ja')) return 'ja';
  if (navLang === 'zh-tw' || navLang === 'zh-hk' || navLang === 'zh-mo' || navLang.startsWith('zh-hant')) {
    return 'zh-TW';
  }
  if (navLang.includes('sg') || navLang === 'zh-sg' || navLang === 'en-sg') {
    return 'en-SG';
  }
  if (navLang.startsWith('pt')) return 'pt';
  if (navLang.startsWith('de')) return 'de';
  if (navLang.startsWith('it')) return 'it';
  if (navLang.startsWith('id')) return 'id';
  if (navLang.startsWith('vi')) return 'vi';
  if (navLang.startsWith('th')) return 'th';
  if (navLang === 'en-gb') return 'en-GB';
  if (navLang.startsWith('en')) return 'en';

  return 'en';
}
